// Obtém perguntas aleatórias, opcionalmente filtradas por categoria.
// Exemplos:
// getRandomQuestions(10)
// getRandomQuestions(10, 'Moçambique')

export function getRandomQuestions(amount = 10, category = null) {
  const availableQuestions = questions.filter((question) => {
    return !category || question.category === category
  })

  const shuffledQuestions = [...availableQuestions]

  for (let i = shuffledQuestions.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))

    ;[shuffledQuestions[i], shuffledQuestions[j]] = [
      shuffledQuestions[j],
      shuffledQuestions[i]
    ]
  }

  return shuffledQuestions.slice(0, Math.max(0, amount))
}
